const { test, expect } = require('@playwright/test');
const { randomUUID } = require('node:crypto');
test.use({ actionTimeout: 20000 });
test('dashboard loads current metrics, drills to a ticket and shows responsive period trends', async ({ page }) => {
  const tenant = 'dashboard-' + randomUUID(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.route('**/odata/v4/it-operations/**', route => { const u = new URL(route.request().url()); u.searchParams.set('sap-client', tenant); return route.continue({ url: u.toString() }); });
  await page.goto('/test/flp.html?sap-ui-animationMode=none#app-preview&/Dashboard', { waitUntil: 'domcontentloaded' });
  await expect(page.getByRole('link', { name: /Open tickets/ })).toBeVisible({ timeout: 90000 });
  await page.getByRole('link', { name: /Open tickets/ }).click();
  await expect(page.getByRole('heading', { name: 'Open tickets · 7 supporting records', exact: true })).toBeVisible();
  await page.getByRole('link', { name: /IT-10452/ }).click();
  await expect(page).toHaveURL(/Tickets\(/);
  await expect(page.getByRole('heading', { name: 'IT-10452', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Home', exact: true }).click();
  await page.getByRole('button', { name: /IT Operations Dashboard/ }).click();
  await expect(page.getByRole('combobox', { name: 'Analysis period', exact: true })).toBeEnabled();
  await page.getByRole('combobox', { name: 'Analysis period', exact: true }).press('F4');
  await page.getByRole('option', { name: 'Last 365 days', exact: true }).click();
  await page.getByRole('link', { name: /Average response time/ }).click();
  await expect(page.getByRole('heading', { name: /Average response time.*supporting records/ })).toBeVisible();
  await expect(async () => { await page.getByRole('heading', { name: 'Operational indicators', exact: true }).scrollIntoViewIfNeeded(); }).toPass();
  await page.screenshot({ path: 'test-results/phase-9-dashboard.png', animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(async () => { await page.getByRole('heading', { name: 'Ticket trends', exact: true }).scrollIntoViewIfNeeded(); }).toPass();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/phase-9-dashboard-mobile.png', animations: 'disabled' });
  await page.getByRole('link', { name: /^Created: [1-9]/ }).first().click();
  await expect(page.getByRole('heading', { name: /Tickets created ·/ })).toBeVisible();
  expect(errors).toEqual([]);
});
test('dashboard rejects a partial load and can recover with Refresh', async ({ page }) => {
  let fail = true;
  await page.route('**/odata/v4/it-operations/Stocks?*', route => fail ? route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { code: '503', message: 'Stock service unavailable' } }) }) : route.continue());
  await page.goto('/test/flp.html?sap-ui-animationMode=none#app-preview&/Dashboard', { waitUntil: 'domcontentloaded' });
  await expect(page.getByText('Stock service unavailable', { exact: true })).toBeVisible({ timeout: 90000 });
  await expect(page.getByRole('link', { name: /Open tickets/ })).toHaveCount(0);
  fail = false; await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  await expect(page.getByRole('link', { name: /Open tickets/ })).toBeVisible();
});
test('dashboard asset and consumption records open their canonical pages', async ({ page }) => {
  await page.goto('/test/flp.html?sap-ui-animationMode=none#app-preview&/Dashboard', { waitUntil: 'domcontentloaded' });
  await page.getByRole('link', { name: /Assets under repair/ }).click({ timeout: 90000 });
  await page.locator('[id$="--records"]').getByRole('link').first().click();
  await expect(page).toHaveURL(/Assets\(/);
  await page.getByRole('button', { name: 'Home', exact: true }).click();
  await page.getByRole('button', { name: /IT Operations Dashboard.*Indicators/s }).click();
  await expect(page.getByRole('combobox', { name: 'Analysis period', exact: true })).toBeEnabled();
  await page.getByRole('combobox', { name: 'Analysis period', exact: true }).press('F4');
  await page.getByRole('option', { name: 'Last 365 days', exact: true }).click();
  await page.getByRole('link', { name: /Inventory consumption/ }).click();
  await page.locator('[id$="--records"]').getByRole('link').first().click();
  await expect(page).toHaveURL(/StockTransactions\(/);
});
